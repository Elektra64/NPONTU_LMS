    // Improved animated counters
    document.addEventListener('DOMContentLoaded', () => {
        const counters = document.querySelectorAll('.counter');
        const speed = 200; // Lower is faster
        const animationDuration = 2000; // 2 seconds total

        const animateCounters = () => {
            counters.forEach(counter => {
                const target = +counter.getAttribute('data-target');
                const count = +counter.innerText;
                const increment = target / (animationDuration / 16); // 60fps
                let currentCount = count;

                if (currentCount < target) {
                    counter.innerText = Math.ceil(currentCount + increment);
                    setTimeout(animateCounters, 16); // ~60fps
                } else {
                    counter.innerText = target.toLocaleString(); // Format number
                }
            });
        };

        // Start animation when stats section is in view
        const observer = new IntersectionObserver((entries) => {
            entries.forEach(entry => {
                if (entry.isIntersecting) {
                    animateCounters();
                    observer.unobserve(entry.target);
                }
            });
        }, { threshold: 0.5 });

        const statsSection = document.querySelector('.bg-gray-800');
        if (statsSection) {
            observer.observe(statsSection);
        }
    });
